import random

class ASCII_Art:
    @staticmethod
    def ASCII_Faces(gender:str=None):
        faces = []

        if None == gender:
            faces += ASCII_Art.ASCII_FACES_F
            faces += ASCII_Art.ASCII_FACES_M

        elif 'f' == gender:
            faces = ASCII_Art.ASCII_FACES_F

        elif 'm' == gender:
            faces = ASCII_Art.ASCII_FACES_M
        
        return faces

    @staticmethod
    def ASCII_Face(gender:str=None, i:int=None):
        faces = ASCII_Art.ASCII_Faces(gender)

        if None == i:
            i = random.randint(0, len(faces)-1)
        
        return faces[i]

